def main() -> None:
    for bank in (1, 2, 3):
        folder = MONTH / f"revision-{bank}"
        qpath = folder / "QUESTIONS.md"
        apath = folder / "ANSWERS.md"
        existing_q = qpath.read_text(encoding="utf-8")
        existing_a = apath.read_text(encoding="utf-8")
        start = max(q_number(existing_q), default=0) + 1
        qpath.write_text(render_questions(existing_q, bank), encoding="utf-8")
        apath.write_text(existing_a.rstrip() + render_answers(bank, start), encoding="utf-8")
        (folder / "COVERAGE.md").write_text(render_bank_coverage(bank, start), encoding="utf-8")


if __name__ == "__main__":
    main()
