def make_question(idx, fact, bank, rng):
    if bank == 1:
        stems = [
            f"Which statement most accurately identifies {fact['label']}?",
            f"For a foundation classification, {fact['label']} is best represented by:",
            f"Which option preserves the legal or market boundary of {fact['label']}?",
            f"A learner revising securities markets should associate {fact['label']} with:",
        ]
    elif bank == 2:
        stems = [
            f"An Indian investor applies the concept of {fact['label']}. Which conclusion follows?",
            f"A statement-level test of {fact['label']} would support which option?",
            f"Which transaction is consistent with {fact['label']}?",
            f"Which interpretation of {fact['label']} avoids a regulatory or risk-allocation error?",
        ]
    else:
        stems = [
            f"In a close-option comparison, which proposition about {fact['label']} is defensible?",
            f"Consider the mechanism and limitation of {fact['label']}. Which option is correct?",
            f"Which inference keeps the claim, cash-flow, liquidity or regulator boundary of {fact['label']} intact?",
            f"An examiner tests {fact['label']} against a plausible distractor. Which answer survives?",
        ]
    stem = stems[idx % len(stems)]
    opts = [fact["correct"], *fact["wrong"]]
    max_len = max(map(len, opts))
    pads = [
        " in the stated market",
        " for the relevant investor",
        " within the applicable framework",
        " in the transaction described",
    ]
    for i, option in enumerate(opts):
        p = 0
        while len(opts[i]) < max_len - 34:
            opts[i] += pads[p % len(pads)]
            p += 1
    rng.shuffle(opts)
    answer = "ABCD"[opts.index(fact["correct"])]
    return dict(no=idx + 1, stem=stem, options=opts, answer=answer,
                correct=fact["correct"], source=fact["source"], trap=fact["trap"], area=fact["area"])


def write_questions(path, bank, questions):
    lens = {
        1: "foundation distinctions: claims, instruments, vehicles and institutions",
        2: "application: Indian transactions, regulation, risk transmission and investor protection",
        3: "mixed retention: close comparisons, limitations, special securities and dated holds",
    }[bank]
    lines = [
        f"# Topic 08 - revision-{bank} QUESTIONS",
        "",
        "> Answer-free delivery file: no keys, evidence, hints, source labels, rationales or traps are included.",
        "",
        f"> Bank lens: {lens}. Original-only questions; exact PYQs are withheld under provenance and reproduction-rights holds.",
        "",
    ]
    for q in questions:
        lines.append(f"## Q{q['no']}. {q['stem']}")
        for letter, option in zip("ABCD", q["options"]):
            lines.append(f"{letter}. {option}")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def write_answers(path, bank, questions):
    lines = [
        f"# Topic 08 - revision-{bank} ANSWERS",
        "",
        "> Original-only bank. Each item records the correct answer, evidence, four option-specific rationales and an examiner trap. Exact PYQs are not reproduced.",
        "",
    ]
    for q in questions:
        lines.extend([
            f"## Q{q['no']}. Correct answer: {q['answer']}",
            f"**Question:** {q['stem']}",
            f"**Evidence:** {q['source']}",
            f"**Correct proposition:** {q['correct']}",
            "**Option-specific rationales:**",
        ])
        for letter, option in zip("ABCD", q["options"]):
            if letter == q["answer"]:
                lines.append(f"- **{letter}.** Correct — this option states the source-grounded rule: {q['correct']}.")
            else:
                lines.append(f"- **{letter}.** Incorrect — this option says “{option}”; it fails because the controlling rule is: {q['correct']}.")
        lines.extend([f"**Examiner trap:** {q['trap']}", ""])
    path.write_text("\n".join(lines), encoding="utf-8")


