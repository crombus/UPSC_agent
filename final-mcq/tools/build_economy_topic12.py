def prepare_bank(bank_no, source_items):
    rng = random.Random(12000 + bank_no * 7919)
    bank = []
    for item in source_items:
        options = [item["correct"], *item["wrongs"]]
        rng.shuffle(options)
        key = "ABCD"[options.index(item["correct"])]
        row = dict(item)
        row["options"] = options
        row["key"] = key
        bank.append(row)
    return bank


