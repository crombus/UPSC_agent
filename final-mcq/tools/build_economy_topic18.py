def render_question(item, bank, number, correct_idx):
    labels = ["A", "B", "C", "D"]
    if bank == 1:
        stem = f"Which statement is most accurate about {item['label']} in India's energy-economy context?"
        prefix = ""
    elif bank == 2:
        stem = (
            f"A policymaker is checking the institutional, economic or measurement boundary of "
            f"{item['label']}. Which inference is most defensible?"
        )
        prefix = "In that setting, "
    else:
        stem = (
            f"Consider a UPSC-style proposition on {item['label']}. Which option best survives "
            f"close scrutiny?"
        )
        prefix = "The best-supported reading is that "
    options = [prefix + item["correct"]] + [prefix + x for x in item["wrongs"]]
    order = list(range(4))
    random.Random(20261003 + bank * 1000 + number).shuffle(order)
    shuffled = [options[i] for i in order]
    answer_position = order.index(0)
    q = [f"## Q{number}. {stem}"]
    for idx, text in enumerate(shuffled):
        q.append(f"{labels[idx]}. {text}")
    return "\n".join(q), answer_position


def render_answer(item, bank, number, answer_position, question_text):
    labels = ["A", "B", "C", "D"]
    lines = [
        f"## Q{number}. Correct answer: {labels[answer_position]}",
        f"**Question:** {question_text.splitlines()[0][7:]}",
        f"**Correct proposition:** {item['correct']}",
        f"**Evidence:** {item['evidence']}",
        "**Option-specific rationales:**",
    ]
    opts = [item["correct"]] + item["wrongs"]
    order = list(range(4))
    random.Random(20261003 + bank * 1000 + number).shuffle(order)
    for visible_idx, source_idx in enumerate(order):
        label = labels[visible_idx]
        if source_idx == 0:
            lines.append(
                f"- **{label}.** Correct — {item['correct']} This preserves the relevant "
                "institutional, measurement, market or policy boundary."
            )
        else:
            lines.append(
                f"- **{label}.** Incorrect — {opts[source_idx]} It fails because the supported "
                f"proposition is: {item['correct']}"
            )
    lines.append(f"**Examiner trap:** {item['trap']}")
    lines.append("")
    return "\n".join(lines)


